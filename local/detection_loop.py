"""
Task 1.3: process newly captured frames with YOLOv8.

The process watches the frames/ directory produced by task 1.2.
Original images are never moved or modified.

For every new frame:
    1. Count people with YOLOv8.
    2. Append timestamp and person count to detections.csv.
    3. Save an annotated copy in the current execution directory.

Run from the project root:
    python -m local.detection_loop \
        --run-dir results/local/<execution> \
        --start-time <unix-timestamp>
"""
from __future__ import annotations

import argparse
import time
from datetime import datetime
from pathlib import Path

from dotenv import load_dotenv

from common.annotate import annotate_people
from common.count_people import (
    DetectionError,
    count_people,
    load_model,
)
from common.image import (
    ImageDecodeError,
    ImageEncodeError,
)
from common.results import append_result


FRAMES_DIR = Path("frames")

POLL_INTERVAL_SECONDS = 0.2

# capture_loop.py writes directly with Path.write_bytes().
# Waiting briefly avoids reading a JPEG while it is still being written.
MIN_FILE_AGE_SECONDS = 0.25

FRAME_NAME_FORMAT = "%Y%m%d_%H%M%S"


def _arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Count people in frames captured by task 1.2"
    )

    parser.add_argument(
        "--run-dir",
        type=Path,
        required=True,
        help="Directory where this execution stores its results",
    )

    parser.add_argument(
        "--start-time",
        type=float,
        required=True,
        help="Unix timestamp marking the beginning of this execution",
    )

    parser.add_argument(
        "--max-frames",
        type=int,
        default=None,
        help="Stop after processing N frames",
    )

    return parser.parse_args()


def _find_pending_frames(
    start_time: float,
    processed: set[Path],
) -> list[Path]:
    """
    Return frames created during this execution that have not been processed.

    Existing images from previous executions remain in frames/ but are ignored.
    """
    now = time.time()
    pending: list[Path] = []

    for frame_path in sorted(FRAMES_DIR.glob("*.jpg")):
        if frame_path in processed:
            continue

        try:
            file_stats = frame_path.stat()
        except FileNotFoundError:
            continue

        # Ignore frames that existed before this execution.
        if file_stats.st_mtime < start_time:
            continue

        # capture_loop.py writes directly to the final .jpg path.
        # Give the writer a short time to finish before reading it.
        if now - file_stats.st_mtime < MIN_FILE_AGE_SECONDS:
            continue

        pending.append(frame_path)

    return pending


def _capture_timestamp(frame_path: Path) -> str:
    """
    Recover the capture timestamp from the filename generated by capture_loop.

    capture_loop names files as:
        YYYYMMDD_HHMMSS.jpg
    """
    try:
        captured_at = datetime.strptime(
            frame_path.stem,
            FRAME_NAME_FORMAT,
        )
    except ValueError as exc:
        raise ValueError(
            f"Unexpected frame filename: {frame_path.name}"
        ) from exc

    # The datetime stored in the filename is local time.
    # astimezone() attaches the machine's local timezone.
    return captured_at.astimezone().isoformat(
        timespec="seconds"
    )


def main() -> None:
    args = _arguments()

    load_dotenv()

    if args.max_frames is not None and args.max_frames <= 0:
        raise SystemExit("--max-frames must be positive")

    run_dir = args.run_dir
    annotated_dir = run_dir / "annotated"
    csv_path = run_dir / "detections.csv"

    FRAMES_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    annotated_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    print("Loading YOLOv8 model...")
    load_model()

    print(f"Watching original frames in: {FRAMES_DIR}")
    print(f"Saving results in: {run_dir}")

    processed: set[Path] = set()
    processed_count = 0

    try:
        while (
            args.max_frames is None
            or processed_count < args.max_frames
        ):
            pending_frames = _find_pending_frames(
                start_time=args.start_time,
                processed=processed,
            )

            if not pending_frames:
                time.sleep(POLL_INTERVAL_SECONDS)
                continue

            for frame_path in pending_frames:
                if (
                    args.max_frames is not None
                    and processed_count >= args.max_frames
                ):
                    break

                try:
                    jpeg = frame_path.read_bytes()

                    n_people, boxes = count_people(jpeg)

                    annotated = annotate_people(
                        jpeg,
                        boxes,
                    )

                    annotated_path = (
                        annotated_dir / frame_path.name
                    )

                    annotated_path.write_bytes(
                        annotated
                    )

                    timestamp = _capture_timestamp(
                        frame_path
                    )

                    append_result(
                        csv_path,
                        timestamp=timestamp,
                        n_people=n_people,
                    )

                    processed.add(frame_path)
                    processed_count += 1

                    print(
                        f"[{timestamp}] "
                        f"{frame_path.name}: "
                        f"people={n_people}"
                    )

                except (
                    ImageDecodeError,
                    ImageEncodeError,
                ) as exc:
                    print(
                        f"[IMAGE ERROR] "
                        f"{frame_path.name}: {exc}"
                    )

                    processed.add(frame_path)

                except DetectionError as exc:
                    print(
                        f"[DETECTION ERROR] "
                        f"{frame_path.name}: {exc}"
                    )

                    processed.add(frame_path)

                except ValueError as exc:
                    print(
                        f"[FRAME ERROR] "
                        f"{frame_path.name}: {exc}"
                    )

                    processed.add(frame_path)

    except KeyboardInterrupt:
        print("\nDetection stopped")


if __name__ == "__main__":
    main()