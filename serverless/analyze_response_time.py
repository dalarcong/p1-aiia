"""Analyze serverless response-time measurements."""

from __future__ import annotations

import argparse
import csv
import statistics
from pathlib import Path

import numpy as np


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Analyze serverless response-time metrics"
    )
    parser.add_argument(
        "--csv",
        default="results/serverless/detection_efficiency.csv",
        help="CSV generated by evaluate_detection.py",
    )
    return parser.parse_args()


def summarize(name: str, values: list[float]) -> None:
    print(f"\n{name}")
    print(f"  samples:  {len(values)}")
    print(f"  mean:     {statistics.mean(values):.2f} ms")
    print(f"  median:   {statistics.median(values):.2f} ms")
    print(f"  p95:      {np.percentile(values, 95):.2f} ms")
    print(f"  min:      {min(values):.2f} ms")
    print(f"  max:      {max(values):.2f} ms")
    print(f"  stdev:    {statistics.stdev(values):.2f} ms")


def main() -> None:
    args = parse_args()
    csv_path = Path(args.csv)

    vision_ms = []
    processing_ms = []
    e2e_ms = []

    with csv_path.open(
        newline="",
        encoding="utf-8",
    ) as handle:
        reader = csv.DictReader(handle)

        for row in reader:
            if row["status"] != "ok":
                continue

            vision_ms.append(float(row["vision_ms"]))
            processing_ms.append(float(row["processing_ms"]))
            e2e_ms.append(float(row["e2e_ms"]))

    if not e2e_ms:
        raise SystemExit("No successful measurements found.")

    summarize("Azure AI Vision", vision_ms)
    summarize("Function processing", processing_ms)
    summarize("End-to-end response", e2e_ms)

    overhead = [
        e2e - processing
        for e2e, processing in zip(
            e2e_ms,
            processing_ms,
        )
    ]

    summarize(
        "Serverless overhead (E2E - processing)",
        overhead,
    )

    print("\nRelative contribution")

    print(
        "  Vision / Function: "
        f"{statistics.mean(vision_ms) / statistics.mean(processing_ms) * 100:.1f}%"
    )

    print(
        "  Function / E2E:    "
        f"{statistics.mean(processing_ms) / statistics.mean(e2e_ms) * 100:.1f}%"
    )


if __name__ == "__main__":
    main()