"""Evaluate Azure AI Vision person-counting efficiency.

Uploads manually labelled frames to Azure Blob Storage, waits for the
corresponding result JSON generated by the Azure Function and compares
the Azure count against the ground truth.

Run from the project root:

    python -m serverless.evaluate_detection \
        --ground-truth calibration/ground_truth.csv \
        --frames-dir calibration/frames
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import time
import uuid
from pathlib import Path

from azure.core.exceptions import ResourceNotFoundError
from azure.storage.blob import BlobServiceClient, ContentSettings
from dotenv import load_dotenv


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Evaluate Azure AI Vision person counting"
    )

    parser.add_argument(
        "--ground-truth",
        required=True,
        help="CSV containing filename and manual person count",
    )

    parser.add_argument(
        "--frames-dir",
        required=True,
        help="Directory containing the labelled JPEG frames",
    )

    parser.add_argument(
        "--output",
        default="results/serverless/detection_efficiency.csv",
        help="Output CSV",
    )

    parser.add_argument(
        "--filename-column",
        default="frame",
        help="Ground-truth CSV column containing the frame filename",
    )

    parser.add_argument(
        "--count-column",
        default="n_real",
        help="Ground-truth CSV column containing the manual count",
    )

    parser.add_argument(
        "--timeout",
        type=float,
        default=120.0,
        help="Maximum seconds to wait for each Azure result",
    )

    return parser.parse_args()


def wait_for_result(
    container_client,
    blob_name: str,
    timeout: float,
) -> tuple[dict, float]:
    """Wait until the Function writes the JSON result."""

    started = time.perf_counter()

    while time.perf_counter() - started < timeout:
        blob_client = container_client.get_blob_client(blob_name)

        try:
            data = blob_client.download_blob().readall()

            elapsed_ms = (
                time.perf_counter() - started
            ) * 1000.0

            return json.loads(data), elapsed_ms

        except ResourceNotFoundError:
            time.sleep(0.5)

    raise TimeoutError(
        f"Timed out waiting for Azure result: {blob_name}"
    )


def main() -> None:
    args = parse_args()
    load_dotenv()

    connection_string = os.environ[
        "AZURE_STORAGE_CONNECTION_STRING"
    ]

    raw_container_name = os.getenv(
        "AZURE_RAW_CONTAINER",
        "documents",
    )

    result_container_name = os.getenv(
        "AZURE_RESULTS_CONTAINER",
        "results",
    )

    frames_dir = Path(args.frames_dir)
    ground_truth_path = Path(args.ground_truth)
    output_path = Path(args.output)

    blob_service = BlobServiceClient.from_connection_string(
        connection_string
    )

    raw_container = blob_service.get_container_client(
        raw_container_name
    )

    result_container = blob_service.get_container_client(
        result_container_name
    )

    # Unique prefix prevents collisions with previous experiments.
    run_id = uuid.uuid4().hex[:8]

    rows = []

    with ground_truth_path.open(
        newline="",
        encoding="utf-8",
    ) as handle:
        reader = csv.DictReader(handle)

        if args.filename_column not in reader.fieldnames:
            raise ValueError(
                f"Column '{args.filename_column}' "
                f"not found in {ground_truth_path}"
            )

        if args.count_column not in reader.fieldnames:
            raise ValueError(
                f"Column '{args.count_column}' "
                f"not found in {ground_truth_path}"
            )

        ground_truth_rows = list(reader)

    total = len(ground_truth_rows)

    print(
        f"Evaluating {total} frames "
        f"(run_id={run_id})"
    )

    for index, gt_row in enumerate(
        ground_truth_rows,
        start=1,
    ):
        filename = gt_row[args.filename_column]
        ground_truth = int(gt_row[args.count_column])

        frame_path = frames_dir / filename

        if not frame_path.exists():
            raise FileNotFoundError(
                f"Frame not found: {frame_path}"
            )

        image_data = frame_path.read_bytes()

        # Keep the original filename visible while ensuring that
        # every evaluation run creates new BlobCreated events.
        azure_name = f"eval_{run_id}_{filename}"

        input_blob_name = f"in/{azure_name}"
        result_blob_name = f"{azure_name}.json"

        print(
            f"[{index}/{total}] {filename}: "
            f"GT={ground_truth}",
            end="",
            flush=True,
        )

        upload_started = time.perf_counter()

        raw_container.upload_blob(
            name=input_blob_name,
            data=image_data,
            overwrite=False,
            content_settings=ContentSettings(
                content_type="image/jpeg"
            ),
        )

        try:
            result, wait_ms = wait_for_result(
                result_container,
                result_blob_name,
                args.timeout,
            )

            e2e_ms = (
                time.perf_counter() - upload_started
            ) * 1000.0

            predicted = int(result["n_people"])

            signed_error = predicted - ground_truth
            absolute_error = abs(signed_error)

            rows.append(
                {
                    "filename": filename,
                    "ground_truth": ground_truth,
                    "n_people_azure": predicted,
                    "signed_error": signed_error,
                    "absolute_error": absolute_error,
                    "vision_ms": result.get(
                        "vision_ms",
                        "",
                    ),
                    "processing_ms": result.get(
                        "processing_ms",
                        "",
                    ),
                    "e2e_ms": round(e2e_ms, 2),
                    "status": "ok",
                }
            )

            print(
                f" -> Azure={predicted}, "
                f"|error|={absolute_error}"
            )

        except TimeoutError:
            rows.append(
                {
                    "filename": filename,
                    "ground_truth": ground_truth,
                    "n_people_azure": "",
                    "signed_error": "",
                    "absolute_error": "",
                    "vision_ms": "",
                    "processing_ms": "",
                    "e2e_ms": "",
                    "status": "timeout",
                }
            )

            print(" -> TIMEOUT")

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    fieldnames = [
        "filename",
        "ground_truth",
        "n_people_azure",
        "signed_error",
        "absolute_error",
        "vision_ms",
        "processing_ms",
        "e2e_ms",
        "status",
    ]

    with output_path.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=fieldnames,
        )

        writer.writeheader()
        writer.writerows(rows)

    successful = [
        row
        for row in rows
        if row["status"] == "ok"
    ]

    if not successful:
        raise SystemExit(
            "No frames were processed successfully."
        )

    n = len(successful)

    mae = sum(
        row["absolute_error"]
        for row in successful
    ) / n

    bias = sum(
        row["signed_error"]
        for row in successful
    ) / n

    exact = sum(
        row["absolute_error"] == 0
        for row in successful
    )

    within_one = sum(
        row["absolute_error"] <= 1
        for row in successful
    )

    exact_accuracy = exact / n * 100
    within_one_accuracy = within_one / n * 100

    print()
    print("=== Detection efficiency ===")
    print(f"Frames processed:       {n}/{total}")
    print(f"MAE:                    {mae:.3f} people/frame")
    print(f"Bias:                   {bias:+.3f} people/frame")
    print(f"Exact count accuracy:   {exact_accuracy:.1f}%")
    print(f"Error <= 1 person:      {within_one_accuracy:.1f}%")
    print()
    print(f"Results written to: {output_path}")


if __name__ == "__main__":
    main()